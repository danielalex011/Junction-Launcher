'use strict';
// `npm run vendor`: copies the Lucide category icons, the skinview3d browser bundle, the Pixelify Sans heading font (OFL) and the licenses of the code inside them from node_modules
// into src/renderer/vendor/. Run it after changing the skinview3d version, then commit the result.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'renderer', 'vendor');
const nm = (...p) => path.join(root, 'node_modules', ...p);
const files = [
  [nm('skinview3d', 'bundles', 'skinview3d.bundle.js'), 'skinview3d.bundle.js'],
  [nm('skinview3d', 'LICENSE'), 'LICENSE-skinview3d.txt'],
  [nm('three', 'LICENSE'), 'LICENSE-three.txt'], // three.js is bundled inside skinview3d
  [nm('skinview-utils', 'LICENSE'), 'LICENSE-skinview-utils.txt'], // so is skinview-utils
  [nm('@fontsource', 'pixelify-sans', 'files', 'pixelify-sans-latin-700-normal.woff2'), 'PixelifySans-700.woff2'], // heading font (SIL Open Font License 1.1)
  [nm('@fontsource', 'pixelify-sans', 'LICENSE'), 'LICENSE-PixelifySans.txt'],
];
fs.mkdirSync(out, { recursive: true });
for (const [from, name] of files) {
  if (!fs.existsSync(from)) { console.error(`Missing ${path.relative(root, from)}. Run npm install first.`); process.exit(1); }
  fs.copyFileSync(from, path.join(out, name));
  console.log(`vendor/${name}`);
}
console.log(`skinview3d ${require(nm('skinview3d', 'package.json')).version}, three ${require(nm('three', 'package.json')).version}`);

// ---- category icons (Lucide, ISC licence): the Browse filter panel's tiles. Only the icons listed here are copied, as small SVG fragments.
// Left: the shared category key (see keyOf in src/core/sources/categories.js). Right: the Lucide icon's file name.
