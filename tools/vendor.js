  social: 'users', storage: 'package', technology: 'cpu', transportation: 'truck', utility: 'wrench', worldgeneration: 'mountain-snow',
  challenging: 'target', combat: 'swords', kitchensink: 'layers', lightweight: 'feather', multiplayer: 'users', quests: 'scroll',
  audio: 'volume-2', blocks: 'box', coreshaders: 'sparkles', entities: 'ghost', environment: 'trees', fonts: 'type', gui: 'app-window',
  items: 'backpack', locale: 'languages', modded: 'puzzle', models: 'shapes', realistic: 'eye', simplistic: 'minimize-2', themed: 'palette',
  tweaks: 'settings-2', vanillalike: 'blocks', '8x': 'grid-3x3', '16x': 'grid-3x3', '32x': 'grid-3x3', '48x': 'grid-3x3', '64x': 'grid-3x3',
  '128x': 'grid-3x3', '256x': 'grid-3x3', '512xorhigher': 'grid-3x3', '8xorlower': 'grid-3x3',
  cartoon: 'brush', fantasy: 'wand-sparkles', foliage: 'leaf', high: 'rocket', medium: 'gauge', low: 'zap', potato: 'sprout',
  pathtracing: 'sun', pbr: 'lightbulb', reflections: 'waves', screenshot: 'camera', semirealistic: 'eye', atmosphere: 'cloud', coloredlighting: 'lightbulb',
